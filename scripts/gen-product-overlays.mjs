/** @param {Record<string, object>} pack */
function packBlock(name, pack) {
  const entries = Object.entries(pack)
    .map(([k, v]) => entry(k, /** @type {any} */ (v)))
    .join("\n");
  return `const ${name}: OverlayPack = {\n${entries}\n};`;
}

