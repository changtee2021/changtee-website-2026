export function getProductContent(
  categorySlug: string,
  productSlug: string,
): ProductContent | null {
  const found = getProduct(categorySlug, productSlug);
  if (!found) return null;

  const k = key(categorySlug, productSlug);
  const base = CONTENT[k]
    ? { ...CONTENT[k], faqs: CONTENT[k].faqs ?? [] }
    : fallbackContent(found.category, found.product);

  const bankFaqs = PRODUCT_FAQS[k];
  const faqs =
    bankFaqs && bankFaqs.length === 5
      ? bankFaqs
      : base.faqs.length >= 5
        ? base.faqs.slice(0, 5)
        : [
            ...base.faqs,
            ...fallbackContent(found.category, found.product).faqs,
          ].slice(0, 5);

  // Prefer bank; if still short, pad from fallback generic FAQs
  let resolved = faqs;
  if (resolved.length < 5) {
    const pad = fallbackContent(found.category, found.product).faqs;
    resolved = [...resolved, ...pad].slice(0, 5);
  }

  return {
    tagline: base.tagline,
    body: base.body,
    highlights: base.highlights,
    suitableFor: base.suitableFor,
    care: base.care,
    faqs: resolved,
  };
}

