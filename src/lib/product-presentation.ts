function buildGallery(
  hero: string,
  texture: string,
  lifestyle: string,
  context: string,
): string[] {
  const unique: string[] = [];
  for (const src of [hero, texture, lifestyle, context]) {
    if (src && !unique.includes(src)) unique.push(src);
  }
  while (unique.length < 2) unique.push(hero);
  return unique;
}

function mergeMaterials(
  base: CategoryDefaults["materials"],
  override?: ProductPresentation["materials"],
): ProductPresentation["materials"] {
  return override ?? base;
}

export function getProductPresentation(
  categorySlug: string,
  productSlug: string,
): ProductPresentation | null {
  const found = getProduct(categorySlug, productSlug);
  if (!found) return null;

  const content = getProductContent(categorySlug, productSlug);
  if (!content) return null;

  const { category, product } = found;
  const defaults = CATEGORY_DEFAULTS[category.slug];
  if (!defaults) return null;

  const overrideKey = `${categorySlug}/${productSlug}`;
  const override = PRODUCT_OVERRIDES[overrideKey];

  const roomStyleIds = override?.roomStyleIds ?? defaults.roomStyleIds;
  const roomStyles = resolveRoomStyles(categorySlug, roomStyleIds);

  const hero = childImage(category, product);
  const texture = CATEGORY_TEXTURE[category.slug] ?? hero;
  const ctx = CATEGORY_CONTEXT[category.slug];
  const lifestyle =
    ctx?.living ?? roomStyles[0]?.image ?? hero;
  const contextRoom =
    ctx?.room ?? roomStyles[1]?.image ?? roomStyles[0]?.image ?? hero;
  const gallery = buildGallery(hero, texture, lifestyle, contextRoom);

  const assets: DetailAsset = {
    hero: override?.assets?.hero ?? hero,
    texture: override?.assets?.texture ?? texture,
    lifestyle: override?.assets?.lifestyle ?? lifestyle,
    context: override?.assets?.context ?? contextRoom,
    gallery: override?.assets?.gallery ?? gallery,
  };

  const stats = override?.benefitStats ?? defaults.benefitStats;
  const benefitCards: BenefitCard[] = [
    {
      label: "รายละเอียดพื้นผิว",
      detail: `ผิวสัมผัสและลายวัสดุของ${product.name} — ดูใกล้ก่อนเลือกผ้า/รุ่น`,
      image: assets.texture,
    },
    {
      label: stats[0]?.label ?? content.highlights[0] ?? "ใช้งานในห้องจริง",
      detail:
        stats[0]?.detail ??
        `ตัวอย่าง${product.name} ในห้องนั่งเล่น — ดูบรรยากาศก่อนตัดสินใจ`,
      image: assets.lifestyle,
    },
    {
      label: stats[1]?.label ?? content.highlights[1] ?? "เหมาะกับห้องนอน/มุมพัก",
      detail:
        stats[1]?.detail ??
        `มุมห้องที่เหมาะกับ${product.name} — จับคู่สไตล์กับพื้นที่ใช้งาน`,
      image: assets.context,
    },
  ];

  const seoTitle =
    override?.seoTitle ?? `${product.name} ${category.name}`;

  const seoDescription =
    override?.seoDescription ??
    buildSeoDescription(product, content.tagline);

  const seoKeywords =
    override?.seoKeywords ??
    Array.from(
      new Set([
        product.name,
        category.name,
        product.nameEn,
        category.nameEn,
        ...(defaults.baseKeywords ?? []),
        siteConfig.name,
      ].filter((k): k is string => Boolean(k))),
    );

  return {
    seoTitle,
    seoDescription,
    seoKeywords,
    specs: override?.specs ?? defaults.specs,
    swatches: override?.swatches ?? buildSwatches(assets.texture, roomStyles),
    roomStyles,
    consultantIntro:
      override?.consultantIntro ??
      defaults.consultantIntro ??
      `ทีมช่างตี๋แนะนำ${product.name} ให้เข้ากับหน้างานจริง — วัดก่อนตัด ติดตั้งครบวงจร`,
    consultantSteps: override?.consultantSteps ?? defaults.consultantSteps,
    benefitStats: stats,
    benefitCards,
    materials: mergeMaterials(defaults.materials, override?.materials),
    assets,
  };
}

export function getProductJsonLd(
  categorySlug: string,
  productSlug: string,
): Record<string, unknown> | null {
  const found = getProduct(categorySlug, productSlug);
  if (!found) return null;

  const content = getProductContent(categorySlug, productSlug);
  const presentation = getProductPresentation(categorySlug, productSlug);
  if (!content || !presentation) return null;

  const { category, product } = found;
  const base = siteConfig.url.replace(/\/$/, "");
  const productUrl = `${base}/products/${category.slug}/${product.slug}`;
  const categoryUrl = `${base}/products/${category.slug}`;
  const image = presentation.assets.hero;

  // Quote-only catalog: Product without Offer (incomplete Offer+no price is invalid for rich results).
  // Also expose Service so local-service intent is clear.
  const productLd = {
    "@type": ["Product", "Service"],
    name: `${product.name} ${category.name}`,
    description: presentation.seoDescription,
    image: [`${base}${image}`],
    brand: {
      "@type": "Brand",
      name: siteConfig.name,
    },
    url: productUrl,
    category: category.name,
    provider: {
      "@type": "Organization",
      name: siteConfig.legalName,
      url: base,
    },
    areaServed: "TH",
    potentialAction: {
      "@type": "OrderAction",
      target: `${base}/quote`,
      name: "ขอใบเสนอราคา",
    },
  };

  const faqLd = {
    "@type": "FAQPage",
    mainEntity: content.faqs.map((faq) => ({
      "@type": "Question",
      name: faq.q,
      acceptedAnswer: {
        "@type": "Answer",
        text: faq.a,
      },
    })),
  };

  const breadcrumbLd = {
    "@type": "BreadcrumbList",
    itemListElement: [
      {
        "@type": "ListItem",
        position: 1,
        name: "สินค้า/บริการ",
        item: `${base}/products`,
      },
      {
        "@type": "ListItem",
        position: 2,
        name: category.name,
        item: categoryUrl,
      },
      {
        "@type": "ListItem",
        position: 3,
        name: product.name,
        item: productUrl,
      },
    ],
  };

  return {
    "@context": "https://schema.org",
    "@graph": [productLd, faqLd, breadcrumbLd],
  };
}

