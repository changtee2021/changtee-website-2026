function resolveRoomStyles(
  categorySlug: string,
  ids: string[],
): RoomStyleGuide[] {
  const overlay = CATEGORY_STYLE_OVERLAY[categorySlug] ?? {};
  return ids
    .map((id) => {
      const base = ROOM_STYLE_MAP[id];
      if (!base) return null;
      const over = overlay[id];
      return {
        ...base,
        ...over,
        id: base.id,
        name: base.name,
        nameEn: base.nameEn,
        image: categoryStyleImage(categorySlug, id),
      } satisfies RoomStyleGuide;
    })
    .filter((s): s is RoomStyleGuide => Boolean(s))
    .slice(0, 3);
}

function clampSeoDescription(text: string): string {
  const normalized = text.replace(/\s+/g, " ").trim();
  if (normalized.length <= 160) {
    if (normalized.length >= 140) return normalized;
    const pad = " วัดหน้างานฟรีกับช่างตี๋";
    const next = `${normalized}${normalized.endsWith(".") ? "" : "."}${pad}`;
    return next.length <= 160 ? next : next.slice(0, 160);
  }
  return `${normalized.slice(0, 157).trimEnd()}…`;
}

function buildSeoDescription(
  product: ProductChild,
  contentTagline: string,
): string {
  const core = `${contentTagline} ${product.summary} นัดวัดหน้างานฟรีกับช่างตี๋`;
  return clampSeoDescription(core);
}

